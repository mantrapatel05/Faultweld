from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
OUTPUT = ROOT / "frontend" / "src" / "api" / "generated.ts"

sys.path.insert(0, str(BACKEND))

Schema = dict[str, Any]

def openapi_schema() -> Schema:
    from app.main import app

    return app.openapi()


def schema_type(schema: Schema) -> str:
    reference = schema.get("$ref")
    if isinstance(reference, str):
        return reference.rsplit("/", maxsplit=1)[-1]

    alternatives = schema.get("anyOf")
    if isinstance(alternatives, list):
        return " | ".join(schema_type(item) for item in alternatives)

    schema_format = schema.get("format")
    if schema_format == "date-time":
        return "string"

    schema_kind = schema.get("type")
    if schema_kind == "array":
        items = schema.get("items", {})
        return f"{schema_type(items)}[]"
    if schema_kind == "integer" or schema_kind == "number":
        return "number"
    if schema_kind == "boolean":
        return "boolean"
    if schema_kind == "string":
        return "string"
    if schema_kind == "object":
        return "Record<string, unknown>"
    if schema_kind == "null":
        return "null"
    return "unknown"


def render_schema(name: str, schema: Schema) -> str:
    enum_values = schema.get("enum")
    if isinstance(enum_values, list):
        values = "\n".join(f'  | {json.dumps(value)}' for value in enum_values)
        return f"export type {name} =\n{values};"

    properties = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for property_name, property_schema in properties.items():
        optional = "" if property_name in required else "?"
        lines.append(f"  {property_name}{optional}: {schema_type(property_schema)};")
    lines.append("}")
    return "\n".join(lines)


def render_types(openapi: Schema) -> str:
    schemas = openapi["components"]["schemas"]
    rendered = [
        "// This file is generated by scripts/generate_api_types.py. Do not edit manually.",
    ]
    rendered.extend(
        render_schema(name, schemas[name])
        for name in sorted(schemas)
    )
    return "\n\n".join(rendered) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate frontend types from FastAPI OpenAPI.")
    parser.add_argument("--check", action="store_true", help="Fail if the generated file is stale.")
    args = parser.parse_args()

    generated = render_types(openapi_schema())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print(f"{OUTPUT} is stale; run python scripts/generate_api_types.py")
            return 1
        return 0

    OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
